  getLevel(levelNumber) {
    const levelIndex = (levelNumber - 1) % this.levels.length;
    const levelData = JSON.parse(JSON.stringify(this.levels[levelIndex])); // Deep copy
    
    // Ambil 5 soal berdasarkan tingkat kesulitan level (Tier 1 s/d Tier 4+)
    const questions = getQuestionsForLevel(levelNumber, 5);
    levelData.questions = levelData.questionPositions.map((pos, idx) => ({
      x: pos.x,
      y: pos.y,
      data: questions[idx],
      answered: false
    }));

    return levelData;
  }
